/**
 ******************************************************************************
 * @file    mt6816.h
 * @brief   MT6816 磁编码器模块的对外接口声明
 * @details 提供 14 位绝对角度的读取与查询接口：MT6816_UpdateAngle() 完成一次 SPI
 *          读取并刷新模块内缓存，其余 Get 接口只返回最近一次读取结果，不访问硬件。
 *          原始角度单位为一圈 16384(2^14) 个刻度，取值范围 0~16383；校准后的角度取自
 *          16384 项的校准表，单位为细分步(0~51199，51200 细分步 = 1 圈)，未设置校准表
 *          时退化为原始角度(0~16383)。两者量纲不同，切勿混用。
 * @note    读取依赖 SPI1 与片选引脚 PA15(main.h 中的 SPI1_CS_Pin)，需在 20kHz
 *          控制中断中周期性调用以保持角度数据实时。
 ******************************************************************************
 */

#ifndef MT6816_H
#define MT6816_H /**< 包含保护宏：防止本头文件被重复包含 */

#include <stdbool.h>
#include <stdint.h>

#define MT6816_RESOLUTION 16384 /**< 14 位分辨率 = 2^14 = 16384 个原始刻度(0~16383)，也是校准表项数 */

/**
 * @brief  读取一次编码器角度并更新模块内缓存
 * @details 依次发送 0x03(角度)与 0x04(原始角度)命令，拼接两次返回数据后做奇偶校验，
 *          最多重试 3 次；成功后同时刷新原始角度与校准后的角度缓存。
 * @warning SPI 收发为阻塞方式(HAL_MAX_DELAY)且失败最多重试 3 次，本函数又在 20kHz
 *          控制中断中调用，SPI 异常时会拖长中断时间。
 * @warning 校验连续失败时不更新缓存而返回旧值，上层位置积分会因"旧角度"产生误差。
 * @note   仅在控制中断中周期性调用。
 */
uint16_t MT6816_UpdateAngle(void);

/**
 * @brief  获取上一次读取的原始角度(未校准)
 * @note   不访问硬件，直接返回 MT6816_UpdateAngle() 的缓存结果。
 */
uint16_t MT6816_GetRawAngle(void);

/**
 * @brief  获取上一次读取的校准后角度
 *         未设置校准表时等于原始角度(0-16383)。本模块不做范围检查
 * @note   不访问硬件，直接返回 MT6816_UpdateAngle() 的缓存结果。
 */
uint16_t MT6816_GetRectifiedAngle(void);

/**
 * @brief  检查编码器校准数据是否有效
 * @note   判定条件为整张表(16384 项)中不出现 0xFFFF(Flash 擦除态)，需遍历全表。
 */
bool MT6816_IsCalibrated(void);

/**
 * @brief  设置校准数据表指针
 * @note   应在 MT6816_UpdateAngle() 使用校准表之前调用；传入 NULL 表示不做校准。
 *         表共 16384 项，索引为原始角度(0~16383)，元素为该原始角度对应的校正位置
 *         (单位：细分步，0~51199，51200 细分步 = 1 圈)。
 */
void MT6816_SetCalibrationData(uint16_t *cali_data_ptr);

/**
 * @brief  读取一帧角度数据(不解析、不校验)
 * @note   不更新模块缓存，仅用于 SPI 通信自检。
 * @todo   当前工程未调用该函数(链接时被丢弃)，请确认是保留为调试接口还是移除。
 */
uint16_t MT6816_TestRead(void);

#endif /* MT6816_H */
