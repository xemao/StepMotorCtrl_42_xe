/**
 ******************************************************************************
 * @file    tb67h450.h
 * @brief   TB67H450 双 H 桥步进驱动芯片的电流矢量输出接口声明
 * @details 本工程以 "PWM 当 DAC 设定每相电流幅值 + GPIO 设定每相电流方向" 的方式输出
 *          FOC 电流矢量：电角度(0~1023)决定 A/B 两相正弦幅值，电流值(mA)决定矢量幅值，
 *          两相合成即为目标电流矢量。角度一个电周期 = 1024 个刻度，电流单位为 mA。
 * @note    输出接口由 20kHz(50us) 控制中断周期性调用，内部不做阻塞等待。
 ******************************************************************************
 */

#ifndef TB67H450_H
#define TB67H450_H /**< 包含保护宏：防止本头文件被重复包含 */

#include <stdbool.h>
#include <stdint.h>

/**
 * @brief  输出 FOC 电流矢量到两相 H 桥
 * @details 由电角度查正弦表得到 A/B 相正弦值，将电流换算为 12 位 DAC 值后与正弦绝对值
 *          相乘，得到两相 PWM 占空比并写入 TIM2 CH3/CH4，同时按正弦符号设置方向脚。
 *          电流方向(正负)由调用方通过电角度偏移体现。
 * @note    B 相取电角度低 10 位，A 相在此基础上 +256(即超前 90 度)。
 */
void TB67H450_SetFocCurrentVector(uint32_t _directionInCount, int32_t _current_mA);

/**
 * @brief  进入休眠(两相断电)
 * @note   两相 PWM 比较值清零且 AP/AM/BP/BM 四脚全部置低，H 桥输出高阻，电机不输出转矩。
 */
void TB67H450_Sleep(void);

/**
 * @brief  进入刹车(两相绕组短接制动)
 * @note   两相 PWM 比较值清零且 AP/AM/BP/BM 四脚全部置高，H 桥进入制动状态(绕组短接)，
 *         电机被被动制动。
 */
void TB67H450_Brake(void);

#endif
